using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

[InitializeOnLoad]
public static class CameraSettingsSetup
{
    static CameraSettingsSetup() { EditorApplication.delayCall += Setup; }
    [MenuItem("Tools/Dead Shot/Setup Camera Settings")]
    static void Setup()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode) return;
        var scene = UnityEngine.SceneManagement.SceneManager.GetSceneByName("Stage_city");
        if (!scene.isLoaded) return;
        foreach (var keyboard in Object.FindObjectsOfType<KeyBindingSettingsUI>(true))
        {
            if (keyboard.gameObject.scene != scene) continue;
            if (keyboard.cameraSettings != null)
            {
                var existing = keyboard.cameraSettings;
                if(existing.layoutVersion>=3 && existing.layoutVersion<4){Integrate(keyboard,existing);continue;}
                if (existing.layoutVersion < 3 && existing.cameraLayout != null)
                {
                    // Only replace the camera layout generated by this feature; existing keyboard UI is untouched.
                    Undo.DestroyObjectImmediate(existing.cameraLayout);
                    existing.Build(); existing.cameraLayout.SetActive(false);
                    EditorUtility.SetDirty(existing);
                    EditorSceneManager.MarkSceneDirty(scene); EditorSceneManager.SaveScene(scene);
                }
                else if (existing.cameraLayout != null && existing.cameraLayout.activeSelf)
                {
                    existing.cameraLayout.SetActive(false);
                    EditorUtility.SetDirty(existing);
                    EditorSceneManager.MarkSceneDirty(scene); EditorSceneManager.SaveScene(scene);
                }
                continue;
            }
            var camera = Undo.AddComponent<CameraSettingsUI>(keyboard.gameObject);
            camera.owner = keyboard;
            camera.font = keyboard.font;
            camera.controlsLayout = keyboard.transform.Find("Key Bindings Layout")?.gameObject;
            camera.switchCamera = Object.FindObjectOfType<SwitchCamera>(true);
            camera.Build();
            camera.cameraLayout.SetActive(false);
            keyboard.cameraSettings = camera;
            Integrate(keyboard,camera);
            EditorUtility.SetDirty(keyboard); EditorUtility.SetDirty(camera);
            EditorSceneManager.MarkSceneDirty(scene); EditorSceneManager.SaveScene(scene);
            Debug.Log("[CameraSettingsSetup] カメラ比較・動画デモ設定UIをStage_cityに登録しました。", camera);
        }
    }
    static void Integrate(KeyBindingSettingsUI keyboard,CameraSettingsUI camera)
    {
        var layout=keyboard.transform.Find("Key Bindings Layout");
        if(layout==null||camera.cameraLayout==null)return;
        var elements=new System.Collections.Generic.List<GameObject>();
        foreach(var text in camera.cameraLayout.GetComponentsInChildren<TMPro.TMP_Text>(true))
            if(text.text.StartsWith("DEFAULT AIM VIEW")){elements.Add(text.gameObject);break;}
        elements.Add(camera.firstPerson.preview.transform.parent.gameObject);
        elements.Add(camera.thirdPerson.preview.transform.parent.gameObject);
        elements.Add(camera.firstPerson.selectButton.gameObject);
        elements.Add(camera.thirdPerson.selectButton.gameObject);
        elements.Add(camera.selectionAccent.gameObject);
        foreach(var element in elements){Undo.SetTransformParent(element.transform,layout,"Integrate camera content");
            // Existing generated content uses the same 1600x900 top-left coordinates.
            var r=(RectTransform)element.transform;r.localScale=Vector3.one;r.localRotation=Quaternion.identity;
            element.SetActive(false);
        }
        // Restore exact local coordinates after reparenting from the old unscaled layout.
        SetRect(elements[0],0,168,1600,48);
        SetRect(elements[1],45,230,735,400);SetRect(elements[2],820,230,735,400);
        SetRect(elements[3],45,650,735,70);SetRect(elements[4],820,650,735,70);SetRect(elements[5],45,650,5,70);
        camera.cameraElements=elements.ToArray();
        camera.keyboardElements=new[]{layout.Find("Action List Panel").gameObject,layout.Find("Keyboard Panel").gameObject,layout.Find("Rebind Panel").gameObject};
        camera.controlsLayout=layout.gameObject;
        camera.controlsTab=keyboard.tabs[0];camera.cameraTab=keyboard.tabs[1];camera.audioTab=keyboard.tabs[2];camera.displayTab=keyboard.tabs[3];
        camera.tabAccent=(RectTransform)layout.Find("Selected Tab");
        camera.statusText=keyboard.messageText;
        camera.resetButton=keyboard.resetButton;camera.applyButton=keyboard.applyButton;camera.backButton=keyboard.backButton;
        foreach(var text in layout.Find("Footer").GetComponentsInChildren<TMPro.TMP_Text>(true))
            if(text!=keyboard.messageText && text.text.Contains("ホイール"))camera.footerGuide=text;
        camera.cameraLayout.SetActive(false); // unused duplicate shell retained for recovery
        camera.layoutVersion=4;
        EditorUtility.SetDirty(camera);EditorUtility.SetDirty(keyboard);
        EditorSceneManager.MarkSceneDirty(keyboard.gameObject.scene);EditorSceneManager.SaveScene(keyboard.gameObject.scene);
        Debug.Log("[CameraSettingsSetup] Shared header/footer; six camera elements integrated inside existing keyboard layout. v4");
    }
    static void SetRect(GameObject go,float x,float y,float w,float h){var r=(RectTransform)go.transform;r.anchorMin=r.anchorMax=r.pivot=new Vector2(0,1);r.anchoredPosition=new Vector2(x,-y);r.sizeDelta=new Vector2(w,h);}
}
